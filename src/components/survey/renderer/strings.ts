export type RendererStrings = typeof DEFAULT_STRINGS

export function mergeStrings(overrides?: Partial<RendererStrings>): RendererStrings {
  return overrides ? { ...DEFAULT_STRINGS, ...overrides } : DEFAULT_STRINGS
}

/** Replace `{name}` placeholders. Unknown names stay as written. */
export function fmt(template: string, params: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (params[k] !== undefined ? String(params[k]) : m))
}
